def build_recipes(recipe_list, category):
    result = []
    for i, (code, name, ingredients, extra) in enumerate(recipe_list):
        parsed = []
        for ing in ingredients:
            p = parse_ingredient(ing)
            if p:
                parsed.append(p)
        entry = {
            "id": i + 1,
            "code": code,
            "name": name,
            "category": category,
            "ingredients": parsed,
            "extra": extra,
        }
        result.append(entry)
    return result

