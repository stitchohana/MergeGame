#!/usr/bin/env python3
"""Generate recipes.json from the 150-recipe spec. Maps ingredient names→IDs via items.json."""
import json, re
from pathlib import Path

BASE = Path(__file__).parent
ITEMS = json.load(open(BASE / "json_output" / "items.json", encoding="utf-8"))

# Build name→id lookup from regular items + crafted items
name_map = {}
for it in ITEMS["regular"]:
    name_map[it["name"]] = it["id"]
for it in ITEMS.get("launcher", []):
    name_map[it["name"]] = it["id"]
for it in ITEMS.get("crafting", []):
    name_map[it["name"]] = it["id"]

def lookup(name):
    """Find item ID by name."""
    if name in name_map:
        return name_map[name]
    return None

def lookup_by_category(name, level, cat_groups):
    """Find item ID by category name + level. e.g. 灵泉晶+Lv.10 → 10010"""
    if name in cat_groups:
        gid = cat_groups[name]
        base = gid * 1000 + 1  # crude: assume ID = group*1000 + level
        # Actually search in items
        for it in ITEMS["regular"]:
            if it.get("group_id") == gid and it.get("level") == level:
                return it["id"]
    return None

def parse_ingredient(text):
    """Parse various ingredient formats into {id, count} or {code, count} or {name, level, count}"""
    text = text.strip()
    if not text or text == "—":
        return None

    # ── Pattern 1: "Name（code）×count" — cross-reference to another recipe ──
    m = re.match(r"(.+?)（(.+?)）\s*[×xX]\s*(\d+)", text)
    if m:
        raw_name = m.group(1).strip()
        ref_code = m.group(2).strip()
        count = int(m.group(3))

        # ref_code could be e.g. "丹药Lv.4", "修006", "灵032", "酒008"
        # If it's a丹药 Lv reference
        dm = re.match(r"丹药Lv\.(\d+)", ref_code)
        if dm:
            lv = int(dm.group(1))
            return {"id": 22000 + lv, "count": count}

        # If it's another recipe code (修/灵/酒)
        if re.match(r"[修灵酒]\d+", ref_code):
            return {"recipe_code": ref_code, "count": count}

        # Otherwise try name lookup
        item_id = lookup(raw_name)
        if item_id:
            return {"id": item_id, "count": count}
        print(f"  WARN: cross-ref unresolved: {raw_name} ({ref_code})")
        return {"name": raw_name, "count": count}

    # ── Pattern 2: "Name Lv.N × Count" — direct item reference ──
    m = re.match(r"(.+?)Lv\.(\d+)\s*[×xX]\s*(\d+)", text)
    if m:
        raw_name = m.group(1).strip()
        level = int(m.group(2))
        count = int(m.group(3))

        # Try exact name match
        item_id = lookup(raw_name)
        if item_id:
            return {"id": item_id, "count": count}

        # Clean parenthetical notes
        clean = re.sub(r"[（(].+?[）)]", "", raw_name).strip()
        item_id = lookup(clean)
        if item_id:
            return {"id": item_id, "count": count}

        # Category-level fallback: "灵泉晶Lv.10" → group 12, level 10
        cat_groups = {"灵泉晶": 12}
        item_id = lookup_by_category(raw_name, level, cat_groups)
        if item_id:
            return {"id": item_id, "count": count}

        # Known丹药 aliases
        pill_aliases = {
            "聚灵丹": 22002, "培元丹": 22003, "筑基丹": 22004,
            "玉液丹": 22004, "玄冰丹": 22005, "赤阳丹": 22006,
            "青木丹": 22007, "雷音丹": 22008, "地脉丹": 22009,
            "星辉丹": 22010, "紫府金丹": 22011, "九窍还魂丹": 22012,
            "涅槃丹": 22013, "龙灵丹": 22014, "凤血丹": 22015,
            "混沌造化丹": 22016,
        }
        if raw_name in pill_aliases:
            return {"id": pill_aliases[raw_name], "count": count}

        # Generic丹药 Lv.N
        dm = re.match(r"丹药Lv\.(\d+)", raw_name)
        if dm:
            return {"id": 22000 + int(dm.group(1)), "count": count}

        print(f"  WARN: unresolved: {raw_name} Lv.{level}×{count}")
        return {"name": raw_name, "level": level, "count": count}

    # ── Pattern 3: Just "Name×Count" (no level) ──
    m = re.match(r"(.+?)\s*[×xX]\s*(\d+)", text)
    if m:
        raw_name = m.group(1).strip()
        count = int(m.group(2))
        item_id = lookup(raw_name)
        if item_id:
            return {"id": item_id, "count": count}
        print(f"  WARN: no-level unresolved: {raw_name}×{count}")
        return {"name": raw_name, "count": count}

    print(f"  WARN: cannot parse: {text}")
    return None

